-- Повний SQL-скрипт для виконання у Supabase SQL Editor (на 7-9 балів)

create table if not exists public.books (
    id bigint generated by default as identity primary key,
    title text not null,
    author text not null,
    created_at timestamptz not null default now()
);

alter table public.books enable row level security;

-- 5 тестових записів
insert into public.books (title, author)
values
    ('Кобзар', 'Тарас Шевченко'),
    ('Лісова пісня', 'Леся Українка'),
    ('Тигролови', 'Іван Багряний'),
    ('Тіні забутих предків', 'Михайло Коцюбинський'),
    ('Захар Беркут', 'Іван Франко');

-- Дозвіл та політика на читання (SELECT)
grant select on table public.books to anon;

create policy "Public can read books"
on public.books
for select
to anon
using (true);

-- Обмеження довжини полів та дозвіл на додавання (INSERT)
alter table public.books
add constraint books_title_length
check (char_length(trim(title)) between 1 and 150);

alter table public.books
add constraint books_author_length
check (char_length(trim(author)) between 1 and 150);

grant insert (title, author)
on table public.books
to anon;

create policy "Public can add books"
on public.books
for insert
to anon
with check (true);
